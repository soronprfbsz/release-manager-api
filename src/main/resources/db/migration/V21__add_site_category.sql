-- =========================================================
-- V21: 사이트 구분(고객사 / 내부 테스트) 컬럼 추가
--
-- 좌측 트리를 고객사 / 내부 테스트로 그룹핑하기 위한 분류 컬럼.
-- 기존 사이트는 전부 CUSTOMER(고객사)로 들어가며, 내부 테스트 사이트는
-- 배포 후 사용자가 사이트 수정 폼에서 수동 재분류한다(백필 없음).
--
-- DB 테이블은 customer 유지 정책상 그대로 customer 이며 컬럼만 추가한다.
-- =========================================================

ALTER TABLE customer
    ADD COLUMN site_category VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER'
    COMMENT '사이트 구분 (CUSTOMER=고객사 / INTERNAL_TEST=내부 테스트)';
